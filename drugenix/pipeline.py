from __future__ import annotations

import logging
import os
from dataclasses import asdict

from drugenix.aggregation import aggregate, report_to_dict
from drugenix.knowledge_graph import get_knowledge_graph
from drugenix.mechanism_fallback import MIN_DOCS_FOR_LITERATURE_MODE
from drugenix.ner_extraction import extract_entities_from_docs
from drugenix.reasoning import generate_candidates_with_meta
from drugenix.retrieval import retrieve_pubmed
from drugenix.validation import validate_candidates, validation_summary_stats

logger = logging.getLogger(__name__)


def run_pipeline(
    disease_query: str,
    retmax: int = 40,
    top_k: int = 8,
    use_semantic_retrieval: bool = True,
    use_ner: bool = True,
    use_kg: bool = True,
    use_mechanism_fallback: bool = True,
    symptom_derived: bool = False,
) -> dict:
    """
    Full Drugenix agentic pipeline:
      1. Retrieval        - fetch PubMed abstracts (+ optional semantic reranking)
      2. NER Extraction   - extract drug/target entities from abstracts
      3. Reasoning        - generate drug candidates (LLM or heuristic), plus a
                             mechanism-similarity fallback when literature is thin
                             (new/rare disease with little PubMed history yet)
      4. Validation       - rule-based plausibility/evidence/safety checks
      5. Knowledge Graph  - validate candidates against drug-target-disease graph
      6. Aggregation      - Master Agent fuses all evidence into final ranking
    """
    # Data-quality warnings surfaced to the end user (not just server logs)
    # — the difference between "no evidence exists" and "an external API
    # failed" matters a lot to a researcher deciding how much to trust a
    # thin or empty result.
    data_quality_warnings: list[str] = []

    # Stage 1 - Retrieval
    # Wrapped like every other optional stage below: a PubMed outage or a
    # disease term that returns zero hits should degrade to "no literature
    # evidence found" rather than 500ing the whole request. Downstream
    # stages (reasoning, validation, KG, aggregation) already handle an
    # empty doc list cleanly. retrieve_pubmed itself now retries transient
    # NCBI failures internally (see retrieval._http_get), so an exception
    # reaching here means retries were already exhausted — worth flagging.
    try:
        retrieved_docs = retrieve_pubmed(disease_query=disease_query, retmax=retmax, top_k=top_k)
    except Exception as e:
        logger.warning("PubMed retrieval failed for '%s': %s", disease_query, e)
        data_quality_warnings.append(
            f"PubMed retrieval failed after retries ({type(e).__name__}) — results below are based on "
            "zero literature evidence, not a confirmed absence of relevant papers. Try again shortly."
        )
        retrieved_docs = []

    if use_semantic_retrieval and retrieved_docs:
        try:
            from drugenix.semantic_retrieval import semantic_rerank
            retrieved_docs = semantic_rerank(disease_query, retrieved_docs, top_k=top_k)
        except Exception as e:
            logger.warning("Semantic retrieval unavailable, using token-overlap ranking: %s", e)

    # Stage 2 - NER Extraction
    ner_drug_names: set[str] = set()
    ner_result = None
    if use_ner and retrieved_docs:
        try:
            ner_result = extract_entities_from_docs(retrieved_docs)
            ner_drug_names = {d.normalized for d in ner_result.drugs}
        except Exception as e:
            logger.warning("NER extraction unavailable: %s", e)

    # Stage 3 - Reasoning
    candidates, reasoning_meta = generate_candidates_with_meta(disease_query=disease_query, docs=retrieved_docs)
    if reasoning_meta["reasoning_mode"] == "heuristic":
        data_quality_warnings.append(
            "No LLM reasoning was used for this result — it was generated by a much simpler "
            f"deterministic fallback ({reasoning_meta['llm_error']}). Configure an LLM provider "
            "(OPENAI_API_KEY / GEMINI_API_KEY / Ollama) for real reasoning-quality results."
        )

    # Stage 3b - Mechanism-similarity fallback. Kicks in when literature
    # retrieval came back thin (new/emerging/very rare disease with little
    # PubMed history yet) — proposes drugs via target/pathway overlap with
    # related diseases instead of direct citations. Tagged evidence_tier=
    # "mechanistic" and merged in (never replaces literature-backed
    # candidates for the same drug).
    if use_mechanism_fallback and len(retrieved_docs) < MIN_DOCS_FOR_LITERATURE_MODE:
        try:
            from drugenix.mechanism_fallback import generate_mechanistic_candidates
            mechanistic = generate_mechanistic_candidates(disease_query, max_candidates=6)
            existing_names = {c.drug.lower() for c in candidates}
            for mc in mechanistic:
                if mc.drug.lower() not in existing_names:
                    candidates.append(mc)
                    existing_names.add(mc.drug.lower())
            if mechanistic:
                logger.info(
                    "Mechanism fallback added %d candidates for '%s' (only %d PubMed docs retrieved)",
                    len(mechanistic), disease_query, len(retrieved_docs),
                )
        except Exception as e:
            logger.warning("Mechanism-similarity fallback failed for '%s': %s", disease_query, e)

    # Stage 4 - Validation Agent
    validation_results = validate_candidates(
        candidates=candidates, docs=retrieved_docs, disease_query=disease_query,
        symptom_derived=symptom_derived,
    )
    val_stats = validation_summary_stats(validation_results)

    # Stage 5 - Knowledge Graph validation
    kg_results = []
    if use_kg and candidates:
        try:
            kg = get_knowledge_graph()
            kg_results = kg.validate_candidates(candidates, disease_query)
        except Exception as e:
            logger.warning("Knowledge graph validation unavailable: %s", e)

    # Stage 6 - Aggregation / Master Agent
    agg_report = aggregate(
        disease_query=disease_query,
        candidates=candidates,
        validation_results=validation_results,
        kg_results=kg_results,
        ner_drug_names=ner_drug_names,
        docs=retrieved_docs,
    )

    # Stage 7 - ADMET + ClinicalTrials enrichment (top candidates only)
    top_candidate_names = [c.drug for c in candidates[:top_k]]
    admet_scores: dict = {}
    clinical_trials_data: dict = {}

    try:
        from drugenix.admet import score_candidates
        admet_scores = score_candidates(top_candidate_names)
        logger.info("ADMET scored %d/%d candidates", len(admet_scores), len(top_candidate_names))
        # score_candidates() swallows per-drug lookup failures internally (it
        # has to, since "not found in PubChem" is a normal outcome for many
        # biologics/investigational compounds) and never raises here even if
        # PubChem is completely unreachable. A zero-hit result across every
        # candidate is a much stronger signal of a network/API outage than
        # of every single candidate genuinely being absent from PubChem, so
        # surface it explicitly rather than silently showing no ADMET data.
        if top_candidate_names and not admet_scores:
            data_quality_warnings.append(
                "ADMET/drug-likeness scoring (PubChem) returned no data for any candidate — "
                "this usually means PubChem was unreachable, not that these drugs lack "
                "molecular property data. Retry, or verify PubChem connectivity."
            )
    except Exception as e:
        logger.warning("ADMET scoring unavailable: %s", e)
        if top_candidate_names:
            data_quality_warnings.append(f"ADMET/drug-likeness scoring (PubChem) was unavailable: {e}")

    # Phase ranking used below to pick the single most advanced COMPLETED
    # trial per candidate for a results lookup — kept local since it's only
    # needed for that one bounded extra API call, not the whole stage.
    _PHASE_RANK = {
        "Phase 4": 4, "Phase 3": 3, "Phase 2/Phase 3": 3,
        "Phase 2": 2, "Phase 1/Phase 2": 2, "Phase 1": 1,
        "Early Phase 1": 0,
    }

    try:
        from drugenix.clinical_trials import search_trials, get_highest_phase, get_trial_result_outcome
        trial_lookup_failures = 0
        for name in top_candidate_names:
            trials = search_trials(name, disease_query)
            # None means the ClinicalTrials.gov call itself failed (network/
            # timeout/malformed response) — distinct from a successful query
            # that genuinely found zero trials. Conflating the two would let
            # a researcher wrongly conclude a candidate has no trial history
            # just because the API hiccuped.
            lookup_failed = trials is None
            trials = trials or []
            if lookup_failed:
                trial_lookup_failures += 1

            # A COMPLETED trial is not the same as a SUCCESSFUL one — it
            # just means the trial ran its full course. The status field
            # alone can't distinguish "completed and worked" from
            # "completed and failed" (Riluzole/Huntington's, Zolbetuximab/
            # pancreatic cancer both completed on schedule and reported
            # negative primary endpoints). Bounded to ONE extra API call per
            # candidate — only the single most advanced completed trial —
            # to avoid multiplying request volume across every trial found.
            completed = [t for t in trials if str(t.get("status", "")).upper() == "COMPLETED"]
            if completed:
                most_advanced = max(completed, key=lambda t: _PHASE_RANK.get(t.get("phase", ""), -1))
                try:
                    outcome = get_trial_result_outcome(most_advanced.get("nct_id", ""))
                    if outcome:
                        most_advanced["result_outcome"] = outcome
                except Exception as e:
                    logger.debug("Trial result-outcome lookup failed for %s: %s", name, e)

            clinical_trials_data[name] = {
                "trials": trials,
                "trial_count": len(trials),
                "highest_phase": get_highest_phase(trials),
                "has_trials": len(trials) > 0,
                "lookup_failed": lookup_failed,
            }
        logger.info("ClinicalTrials enriched %d candidates", len(clinical_trials_data))
        if top_candidate_names and trial_lookup_failures == len(top_candidate_names):
            data_quality_warnings.append(
                "ClinicalTrials.gov lookups failed for every candidate — this reflects an "
                "API/network issue, not confirmed absence of clinical trial history. Retry shortly."
            )
        elif trial_lookup_failures:
            data_quality_warnings.append(
                f"ClinicalTrials.gov lookup failed for {trial_lookup_failures} of "
                f"{len(top_candidate_names)} candidates — their 'no trials found' status may be "
                f"inaccurate due to an API error rather than a confirmed absence of trials."
            )
    except Exception as e:
        logger.warning("ClinicalTrials enrichment unavailable: %s", e)
        if top_candidate_names:
            data_quality_warnings.append(f"ClinicalTrials.gov enrichment was unavailable: {e}")

    result = {
        "query": disease_query,
        "mode": "disease",
        "runtime": {
            "llm_provider": os.getenv("LLM_PROVIDER", "openai"),
            "openai_model": os.getenv("OPENAI_MODEL", ""),
            "gemini_model": os.getenv("GEMINI_MODEL", ""),
            "ollama_model": os.getenv("OLLAMA_MODEL", ""),
            "custom_model": os.getenv("LLM_MODEL", ""),
            "semantic_retrieval": use_semantic_retrieval,
            "ner_enabled": use_ner,
            "kg_enabled": use_kg,
            "reasoning_mode": reasoning_meta["reasoning_mode"],
        },
        "data_quality_warnings": data_quality_warnings,
        "retrieved": [asdict(d) for d in retrieved_docs],
        "candidates": [asdict(c) for c in candidates],
        "validation": {
            "results": [
                {
                    "drug": r.drug,
                    "status": r.status,
                    "confidence": r.confidence,
                    "adjusted_confidence": r.adjusted_confidence,
                    "checks": r.checks,
                    "warnings": r.warnings,
                    "summary": r.summary,
                }
                for r in validation_results
            ],
            "stats": val_stats,
        },
        "kg_validation": [
            {
                "drug": kr.drug,
                "disease": kr.disease,
                "has_direct_path": kr.has_direct_path,
                "has_indirect_path": kr.has_indirect_path,
                "path_length": kr.path_length,
                "path_nodes": kr.path_nodes,
                "known_targets": kr.known_targets,
                "known_mechanism": kr.known_mechanism,
                "kg_confidence_boost": kr.kg_confidence_boost,
                "explanation": kr.explanation,
            }
            for kr in kg_results
        ],
        "ner": {
            "drugs_found": [d.normalized for d in ner_result.drugs] if ner_result else [],
            "targets_found": [t.normalized for t in ner_result.targets] if ner_result else [],
            "drug_target_pairs": ner_result.drug_target_pairs if ner_result else [],
        },
        "aggregation": report_to_dict(agg_report),
        "admet": admet_scores,
        "clinical_trials": clinical_trials_data,
    }

    # Per-candidate research scorecard: merge a live groundedness score
    # (fraction of the mechanism claim's key terms actually present in the
    # cited PubMed abstracts — same metric scripts/comparative_evaluation.py
    # uses offline) directly onto each ranked candidate, alongside the
    # ADMET/clinical-trial data already attached in the API layer. This is
    # what turns the result into a shortlist a researcher can act on
    # without digging through raw JSON: confidence + groundedness + KG path
    # + ADMET verdict + trial phase, all on one row.
    _MIN_GROUNDEDNESS_FOR_RECOMMENDED = 0.35

    try:
        from drugenix.evaluation import candidate_groundedness
        doc_dicts = result["retrieved"]
        groundedness_by_drug = {
            c["drug"].lower(): round(candidate_groundedness(c, doc_dicts), 3)
            for c in result["candidates"]
        }
        for bucket in ("recommended", "review_needed", "rejected"):
            for c in result["aggregation"].get(bucket, []):
                c["groundedness"] = groundedness_by_drug.get(c["drug"].lower(), 0.0)

        # A candidate can clear the confidence/validation bar and still be
        # weakly grounded (its cited mechanism barely matches the actual
        # abstract text) — that combination shouldn't be presented as a
        # confident "Recommended" result. Demote those to Review Needed
        # instead of silently trusting the confidence score alone.
        agg = result["aggregation"]
        still_recommended, demoted = [], []
        for c in agg.get("recommended", []):
            # Literature-tier candidates need real grounding to stay
            # "Recommended"; mechanistic-tier candidates are exempt from
            # this specific check since they're 0-groundedness by design
            # (aggregation.py already caps and flags them separately).
            if c.get("evidence_tier") == "literature" and c.get("groundedness", 0.0) < _MIN_GROUNDEDNESS_FOR_RECOMMENDED:
                c["explanation"] = (c.get("explanation") or "") + \
                    f". Moved out of Recommended: weak groundedness ({c.get('groundedness', 0.0):.0%}) despite passing the confidence threshold."
                demoted.append(c)
            else:
                still_recommended.append(c)

        if demoted:
            agg["recommended"] = still_recommended
            agg["review_needed"] = demoted + agg.get("review_needed", [])
            passed = len(still_recommended)
            review = len(agg["review_needed"])
            rejected = len(agg.get("rejected", []))
            total = agg.get("total_candidates", passed + review + rejected)
            agg["evidence_summary"] = (
                f"{passed} recommended, {review} need review, {rejected} rejected out of {total} total candidates"
            )
            logger.info(
                "Demoted %d weakly-grounded candidate(s) out of Recommended for '%s': %s",
                len(demoted), disease_query, [c["drug"] for c in demoted],
            )
    except Exception as e:
        logger.warning("Per-candidate groundedness scoring failed: %s", e)

    # Cross-check clinical trial STATUS (not just existence) for the
    # queried disease. A candidate can be well-grounded in PubMed
    # literature purely because the literature describes its mechanism/
    # rationale favorably, while ClinicalTrials.gov separately shows it was
    # already tested in humans for this exact disease and the trial was
    # terminated, withdrawn, or suspended — categorically different
    # information than "no prior trial history" that a researcher needs to
    # see prominently, not buried in the Clinical Trials tab. Real case
    # this catches: IONIS-HTTRx/tominersen for Huntington's disease — Roche
    # discontinued the whole program in 2026 after two separate trials
    # failed to show efficacy, but PubMed papers describing its antisense
    # mechanism still read favorably on their own and say nothing about
    # that outcome.
    _CONCERNING_TRIAL_STATUSES = {"TERMINATED", "WITHDRAWN", "SUSPENDED"}
    try:
        ct_data = result.get("clinical_trials", {})
        agg = result["aggregation"]
        for bucket_name in ("recommended", "review_needed"):
            for c in agg.get(bucket_name, []):
                trial_info = ct_data.get(c["drug"], {})
                trials_list = trial_info.get("trials", [])
                concerning_status = [
                    t for t in trials_list
                    if str(t.get("status", "")).upper() in _CONCERNING_TRIAL_STATUSES
                ]
                # Separate signal from the status check above: a COMPLETED
                # trial with a posted, non-significant primary outcome (see
                # get_trial_result_outcome) — the more common failure
                # pattern, since most negative trials run to completion
                # rather than being stopped early.
                concerning_outcome = [
                    t for t in trials_list
                    if (t.get("result_outcome") or {}).get("primary_outcome_significant") is False
                ]
                if concerning_status or concerning_outcome:
                    notes = []
                    if concerning_status:
                        statuses = ", ".join(sorted({t["status"] for t in concerning_status}))
                        nct_ids = ", ".join(t["nct_id"] for t in concerning_status if t.get("nct_id"))
                        notes.append(f"a {statuses} trial ({nct_ids})")
                    for t in concerning_outcome:
                        outcome = t.get("result_outcome") or {}
                        p_val = outcome.get("p_value")
                        p_note = f", p={p_val}" if p_val else ""
                        notes.append(
                            f"a completed trial ({t.get('nct_id', '')}) with a non-significant "
                            f"primary outcome{p_note}"
                        )
                    c["explanation"] = (c.get("explanation") or "") + (
                        ". CAUTION: ClinicalTrials.gov shows " + "; ".join(notes) +
                        " for this exact drug-disease pair — verify before treating this as a novel "
                        "hypothesis; it may already have been tested in humans and found ineffective "
                        "or unsafe. Automated p-value reading — always confirm against the trial "
                        "record directly."
                    )
                    c["has_concerning_trial_history"] = True

        # A confident top recommendation should never be a drug that
        # already has a terminated/withdrawn/suspended trial for this
        # exact disease sitting unexamined on ClinicalTrials.gov — demote
        # it out of Recommended the same way weak groundedness does above.
        still_recommended2 = [c for c in agg.get("recommended", []) if not c.get("has_concerning_trial_history")]
        demoted2 = [c for c in agg.get("recommended", []) if c.get("has_concerning_trial_history")]
        if demoted2:
            agg["recommended"] = still_recommended2
            agg["review_needed"] = demoted2 + agg.get("review_needed", [])
            passed = len(still_recommended2)
            review = len(agg["review_needed"])
            rejected = len(agg.get("rejected", []))
            total = agg.get("total_candidates", passed + review + rejected)
            agg["evidence_summary"] = (
                f"{passed} recommended, {review} need review, {rejected} rejected out of {total} total candidates"
            )
            logger.info(
                "Demoted %d candidate(s) out of Recommended for '%s' due to terminated/withdrawn/"
                "suspended trial history: %s",
                len(demoted2), disease_query, [c["drug"] for c in demoted2],
            )
    except Exception as e:
        logger.warning("Clinical trial status cross-check failed: %s", e)

    return result


def run_symptom_pipeline(
    symptom_text: str,
    top_conditions: int = 2,
    retmax: int = 40,
    top_k: int = 8,
    use_semantic_retrieval: bool = True,
    use_ner: bool = True,
    use_kg: bool = True,
) -> dict:
    """
    Symptom -> drug-repurposing pipeline:
      1. LLM interprets the symptom description into ranked candidate
         conditions (drugenix.symptom_reasoning).
      2. Each candidate is grounded against live PubMed evidence.
      3. The top `top_conditions` grounded candidates are each run through
         the full disease pipeline (retrieval -> NER -> reasoning ->
         validation -> KG -> aggregation -> ADMET -> trials), same as a
         normal disease query, and merged into one result.

    Every result carries analysis["disclaimer"] — this is a research
    hypothesis tool, not a diagnostic one, and callers (API/frontend)
    must surface that disclaimer to the user.
    """
    from drugenix.planner import ExecutionPlan, PlannerTask, execute_plan
    from drugenix.standard_treatments import get_standard_treatments
    from drugenix.symptom_reasoning import analyze_symptoms

    analysis = analyze_symptoms(symptom_text, max_candidates=5)
    candidates = analysis["candidate_conditions"]

    # Prefer literature-grounded candidates; if none are grounded at all
    # (e.g. a genuinely novel disease with no PubMed history yet), fall
    # back to the LLM's top-confidence guesses rather than returning nothing.
    grounded = [c for c in candidates if c["pubmed_hits"] > 0]
    chosen = (grounded or candidates)[:top_conditions]

    # Deliberately separate from the repurposing candidates below: the
    # repurposing engine excludes drugs already indicated for the queried
    # condition by design (see validation.py's circularity check), which
    # means the "obvious" answer (e.g. paracetamol for fever) never shows
    # up there. This is a small curated reference so it's still visible.
    standard_treatments = get_standard_treatments(symptom_text)

    symptom_llm_error = analysis.get("llm_error")
    base_data_quality_warnings: list[str] = []
    if symptom_llm_error:
        base_data_quality_warnings.append(f"Symptom interpretation LLM call failed: {symptom_llm_error}")

    base_result = {
        "query": f"[symptoms] {symptom_text}",
        "mode": "symptom",
        "symptom_analysis": analysis,
        "standard_treatment_reference": standard_treatments,
        "data_quality_warnings": base_data_quality_warnings,
    }

    if not chosen:
        # No LLM configured / interpretation failed — nothing to run.
        no_candidates_reason = (
            f"No candidate conditions could be derived from the symptoms — {symptom_llm_error}"
            if symptom_llm_error else
            "No candidate conditions could be derived from the symptoms "
            "(no LLM provider configured, or the call failed)."
        )
        base_result.update({
            "retrieved": [], "candidates": [], "validation": {"results": [], "stats": {}},
            "kg_validation": [], "ner": {"drugs_found": [], "targets_found": [], "drug_target_pairs": []},
            "aggregation": {
                "recommended": [], "review_needed": [], "rejected": [], "total_candidates": 0,
                "conflicts_detected": 0, "hallucinations_flagged": 0,
                "evidence_summary": no_candidates_reason,
                "methodology": "Symptom interpretation requires an LLM provider (OPENAI_API_KEY / "
                                "GEMINI_API_KEY / Ollama). Configure LLM_PROVIDER and retry.",
            },
            "admet": {}, "clinical_trials": {},
            "planner": {"is_multi_disease": False, "strategy": "single", "sub_tasks": [], "total_tasks": 0, "completed_tasks": 0, "failed_tasks": 0},
        })
        return base_result

    plan = ExecutionPlan(
        original_query=base_result["query"],
        is_multi_disease=len(chosen) > 1,
        strategy="parallel" if len(chosen) > 1 else "single",
    )
    for i, c in enumerate(chosen):
        raw_condition = c["condition"]
        # "Novel/atypical: X" -> use X as the literal PubMed/LLM query term,
        # but keep the full label visible via the sub-task's source tag.
        clean_condition = (
            raw_condition.split(":", 1)[-1].strip()
            if c.get("is_novel_presentation") else raw_condition
        )
        plan.tasks.append(PlannerTask(
            disease_query=clean_condition or raw_condition,
            priority=i,
            retmax=retmax,
            top_k=top_k,
        ))

    def _pipeline_fn(disease_query: str, retmax: int, top_k: int) -> dict:
        return run_pipeline(
            disease_query=disease_query,
            retmax=retmax,
            top_k=top_k,
            use_semantic_retrieval=use_semantic_retrieval,
            use_ner=use_ner,
            use_kg=use_kg,
            symptom_derived=True,  # no confirmed diagnosis — triggers the high-risk-class safety check
        )

    merged = execute_plan(plan, _pipeline_fn)
    merged["mode"] = "symptom"
    merged["symptom_analysis"] = analysis
    merged["standard_treatment_reference"] = standard_treatments
    return merged
